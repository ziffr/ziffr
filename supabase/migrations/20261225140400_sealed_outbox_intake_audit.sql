-- The Outbox, the intake log and the Audit Log sealed (spec 0028, ticket #246; GLOSSARY: Delivery, Audit Log,
-- Workspace Key). Their words are sealed with the Workspace Key and bound to their row, so the core takes a new row's
-- id first: reserve_row_ids now hands out ids for these tables too, and the Audit Log's id may be given (it was always
-- generated). A sealed name or set of details is longer than the words it holds: the checks allow for that, and the
-- details of an event are then an object holding the sealed text ({"sealed": "w1..."}), still an object.
create or replace function reserve_row_ids(p_table text, p_count integer) returns bigint[] language plpgsql security definer set search_path = public as $$
declare
  seq text;
begin
  if p_table not in ('thread_messages', 'actions', 'deliveries', 'intake_log', 'audit_events') then
    raise exception 'Not a table with sealed columns: %', p_table;
  end if;
  if p_count is null or p_count < 1 or p_count > 1000 then
    raise exception 'Between 1 and 1000 ids at a time.';
  end if;
  seq := pg_get_serial_sequence(p_table, 'id');
  return array(select nextval(seq) from generate_series(1, p_count));
end;
$$;
revoke all on function reserve_row_ids(text, integer) from public, anon, authenticated;

