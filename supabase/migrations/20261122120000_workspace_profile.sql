-- The Workspace Profile (spec 0006, ticket #97; GLOSSARY: Workspace Profile): what kind of business a workspace
-- belongs to. Each column only takes a value from the same fixed list as the core (workspace-profile.ts), so nothing
-- else is stored even by mistake; null until an Owner or Admin sets it. Industry and segment keys are the ones the
-- Metric Catalog tags its Metrics with. Safe to run twice.
alter table workspaces add column if not exists industry text;
alter table workspaces add column if not exists segment text;
alter table workspaces add column if not exists country text;
alter table workspaces add column if not exists currency text;
alter table workspaces add column if not exists employee_band text;
alter table workspaces add column if not exists revenue_band text;

