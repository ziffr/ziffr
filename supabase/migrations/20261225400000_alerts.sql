-- Alerts (spec 0032, ticket #373; GLOSSARY: Alert): a person's own standing request, on one Metric they may see, to
-- be told when its latest value meets a condition. This is the table and its limits; nothing fires yet (ticket 3).
-- `level` holds the number of the condition (a value or a share) and is sealed with the Workspace Key like the other
-- free text (spec 0028), bound to its row, so the core takes the row's id first (reserve_row_ids).
create table alerts (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references workspaces(id) on delete cascade,
  person_id text not null references profiles(id) on delete cascade,
  metric_id bigint not null references metrics(id) on delete cascade,
  kind text not null check (kind in ('share_of_target', 'at_or_above', 'below', 'changed_more', 'missing_after_due')),
  -- A value or a share as text, sealed; null for "missing_after_due". 600 characters leave room for the sealing.
  level text check (char_length(level) <= 600 and ((kind = 'missing_after_due') = (level is null))),
  -- "usual" is the person's Delivery Preference; the rest is one way picked for this Alert.
  delivery text not null default 'usual' check (delivery in ('usual', 'email', 'slack', 'telegram')),
  include_unapproved boolean not null default false,
  -- The person's own switch, kept apart so that no bookkeeping can undo it.
  paused_by_person boolean not null default false,
  -- Why the system does not let it fire, or null: set and cleared by the checks, never by the person.
  paused text check (paused in ('no_access', 'archived', 'no_target', 'no_workflow')),
  -- Since when the person has not seen the Metric: such an Alert is removed after 180 days.
  no_access_since timestamptz,
  state text not null default 'armed' check (state in ('armed', 'fired')),
  fired_period date,
  fired_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index alerts_person_idx on alerts (workspace_id, person_id);
create index alerts_metric_idx on alerts (metric_id);
create index alerts_no_access_idx on alerts (no_access_since) where no_access_since is not null;
alter table alerts enable row level security;
select attach_demo_guard('alerts');

-- Ids for the tables with sealed columns, Alerts too.
create or replace function reserve_row_ids(p_table text, p_count integer) returns bigint[] language plpgsql security definer set search_path = public as $$
declare
  seq text;
begin
  if p_table not in ('thread_messages', 'actions', 'deliveries', 'intake_log', 'audit_events', 'alerts') then
    raise exception 'Not a table with sealed columns: %', p_table;
  end if;
  if p_count is null or p_count < 1 or p_count > 1000 then
    raise exception 'Between 1 and 1000 ids at a time.';
  end if;
  seq := pg_get_serial_sequence(p_table, 'id');
  return array(select nextval(seq) from generate_series(1, p_count));
end;
$$;
revoke all on function reserve_row_ids(text, integer) from public, anon, authenticated;

-- An Alert's id may be given only as reserve_row_ids handed it out, never one ahead of the sequence.
create or replace function alerts_id_reserved() returns trigger language plpgsql as $$
begin
  if new.id > (select last_value from alerts_id_seq) then
    raise exception 'An Alert id must come from reserve_row_ids.';
  end if;
  return new;
end $$;
create trigger alerts_id_reserved before insert on alerts for each row execute function alerts_id_reserved();

-- Makes one Alert for a person within the limits (every row counts, also one on a Metric the person lost sight of, so
-- losing sight and making more cannot get past a limit), in one step under a lock of the Workspace, so Alerts made at once
-- cannot pass a limit together (as claim_pasted_values does). The limits come from the core (alert-limits.ts).
-- Returns 'ok', or the first thing that refuses it: 'not_a_member', 'no_metric', 'person_limit', 'metric_limit' or
-- 'workspace_limit'. The id was taken first (the level is sealed for it).
create or replace function create_alert(p_id bigint, p_ws uuid, p_person text, p_metric bigint, p_kind text, p_level text, p_delivery text, p_include boolean, p_per_person int, p_per_metric int, p_per_workspace int) returns text
language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(hashtext('alerts:' || p_ws::text));
  -- Only a person with a sign-in in this Workspace; a Contact or a stranger has no membership.
  if not exists (select 1 from memberships where workspace_id = p_ws and user_id = p_person) then return 'not_a_member'; end if;
  if not exists (select 1 from metrics where id = p_metric and workspace_id = p_ws) then return 'no_metric'; end if;
  -- Accepted: when a Metric the person lost sight of is deleted its Alerts cascade away and this count drops, which
  -- tells them only that a Metric they once saw is gone (docs/security/threat-model.md, Accepted risks).
  if (select count(*) from alerts where workspace_id = p_ws and person_id = p_person) >= p_per_person then return 'person_limit'; end if;
  if (select count(*) from alerts where workspace_id = p_ws and person_id = p_person and metric_id = p_metric) >= p_per_metric then return 'metric_limit'; end if;
  if (select count(*) from alerts where workspace_id = p_ws) >= p_per_workspace then return 'workspace_limit'; end if;
  insert into alerts (id, workspace_id, person_id, metric_id, kind, level, delivery, include_unapproved)
    values (p_id, p_ws, p_person, p_metric, p_kind, p_level, p_delivery, p_include);
  return 'ok';
end $$;
revoke execute on function create_alert(bigint, uuid, text, bigint, text, text, text, boolean, int, int, int) from public, anon, authenticated;
grant execute on function create_alert(bigint, uuid, text, bigint, text, text, text, boolean, int, int, int) to service_role;

-- Leaving a Workspace, or being removed from it, ends the person's Alerts there in the same step.
create or replace function end_alerts() returns trigger language plpgsql security definer set search_path = public as $$
begin
  delete from alerts where workspace_id = old.workspace_id and person_id = old.user_id;
  return old;
end $$;
create trigger end_alerts after delete on memberships for each row execute function end_alerts();

-- Removes the Alerts that have been without sight of their Metric for more than `p_days` days. Returns how many.
create or replace function remove_stale_alerts(p_days int) returns int language plpgsql security definer set search_path = public as $$
declare n int;
begin
  with gone as (delete from alerts where no_access_since is not null and no_access_since < now() - make_interval(days => p_days) returning 1)
  select count(*) into n from gone;
  return n;
end $$;
revoke execute on function remove_stale_alerts(int) from public, anon, authenticated;
grant execute on function remove_stale_alerts(int) to service_role;
