#!/usr/bin/env node
// Writes the files of Ziffr's own Packs as they come with the app (spec 0052, ticket 4; GLOSSARY: Pack):
// packages/core/src/included-packs.generated.ts, from packs/*.pack.json, so the image carries them and nothing is
// fetched at run time. The file is a list of the files' exact texts, nothing more: the app checks each one like any Pack.
// `node scripts/generate-included-packs.mjs` rewrites it; `--check` writes nothing and exits 1 when it is not what the
// folder gives (the core's included-packs.test.ts runs the same comparison). The file is never edited by hand.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const FILE = "packages/core/src/included-packs.generated.ts";

/** The text of the generated file for the Packs under `root`: every `*.pack.json`, by file name, texts byte for byte. */
export function renderIncluded(root = ROOT) {
  const dir = path.join(root, "packs");
  const names = readdirSync(dir).filter((f) => f.endsWith(".pack.json")).sort();
  const entries = names.map((n) => `  [${JSON.stringify(n.replace(/\.pack\.json$/, ""))}, ${JSON.stringify(readFileSync(path.join(dir, n), "utf8"))}],`);
  return `// GENERATED by scripts/generate-included-packs.mjs from packs/*.pack.json: do not edit it, run \`node scripts/generate-included-packs.mjs\`.
// The files of Ziffr's own Packs (GLOSSARY: Pack) as they come with this release, by file name, as the exact text of each.

/** Every Pack file of the packs folder: its file name without \`.pack.json\`, and its exact text. */
export const INCLUDED_PACK_FILES: readonly (readonly [string, string])[] = [
${entries.join("\n")}
];
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderIncluded();
  const target = path.join(ROOT, FILE);
  if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== text) {
      console.error(`${FILE} is not what packs/ gives: run \`node scripts/generate-included-packs.mjs\`.`);
      process.exit(1);
    }
    console.log(`${FILE} is up to date.`);
  } else {
    writeFileSync(target, text);
    console.log(`Wrote ${FILE}.`);
  }
}
