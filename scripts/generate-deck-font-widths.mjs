// Writes the font width tables of the deck slides (spec 0069; GLOSSARY: Deck, Theme):
// packages/core/src/deck-drawing/font-widths.generated.ts, from the files scripts/deck-fonts.mjs names. The tables hold
// how wide each character is, nothing of its shape. `node scripts/generate-deck-font-widths.mjs` rewrites the file; it
// is never edited by hand.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { DECK_FONTS, deckFontFiles } from "./deck-fonts.mjs";

const FILE = fileURLToPath(new URL("../packages/core/src/deck-drawing/font-widths.generated.ts", import.meta.url));

/** The characters a table covers (Latin, Greek, Cyrillic, punctuation, money, arrows, mathematics, marks). */
const BLOCKS = [[0x20, 0x24f], [0x370, 0x4ff], [0x1e00, 0x1eff], [0x2000, 0x206f], [0x20a0, 0x20c0], [0x2100, 0x214f], [0x2190, 0x22ff], [0x25a0, 0x25ff], [0x2700, 0x27bf]];

/** Reads a TrueType file's units per em and the advance width of a character (tables head, hhea, hmtx, cmap format 4). */
function readFont(path) {
  const f = readFileSync(path);
  const tables = new Map();
  for (let i = 0; i < f.readUInt16BE(4); i++) tables.set(f.toString("latin1", 12 + i * 16, 16 + i * 16), f.readUInt32BE(20 + i * 16));
  const metrics = f.readUInt16BE(tables.get("hhea") + 34);
  const hmtx = tables.get("hmtx");
  const cmap = tables.get("cmap");
  let map = 0;
  for (let i = 0; i < f.readUInt16BE(cmap + 2); i++) {
    const at = cmap + f.readUInt32BE(cmap + 8 + i * 8);
    if (f.readUInt16BE(cmap + 4 + i * 8) === 3 && f.readUInt16BE(at) === 4) map = at;
  }
  if (!map) throw new Error(`${path}: no character map this reader knows`);
  const segments = f.readUInt16BE(map + 6) / 2;
  const glyph = (code) => {
    for (let i = 0; i < segments; i++) {
      if (f.readUInt16BE(map + 14 + i * 2) < code) continue;
      const start = f.readUInt16BE(map + 16 + segments * 2 + i * 2);
      if (start > code) return 0;
      const delta = f.readUInt16BE(map + 16 + segments * 4 + i * 2);
      const offsetAt = map + 16 + segments * 6 + i * 2;
      const offset = f.readUInt16BE(offsetAt);
      if (!offset) return (code + delta) & 0xffff;
      const found = f.readUInt16BE(offsetAt + offset + (code - start) * 2);
      return found ? (found + delta) & 0xffff : 0;
    }
    return 0;
  };
  return {
    unitsPerEm: f.readUInt16BE(tables.get("head") + 18),
    advance: (code) => {
      const g = glyph(code);
      return g ? f.readUInt16BE(hmtx + Math.min(g, metrics - 1) * 4) : null;
    },
  };
}

/** The widths as runs of neighbouring characters: "first:width,width*times;…", the first character in base 36. */
function pack(advance) {
  const runs = [];
  for (const [from, to] of BLOCKS) {
    let run = null;
    for (let code = from; code <= to; code++) {
      const width = advance(code);
      if (width === null) {
        run = null;
        continue;
      }
      if (!run) runs.push((run = { start: code, widths: [] }));
      const last = run.widths[run.widths.length - 1];
      if (last && last.width === width) last.times++;
      else run.widths.push({ width, times: 1 });
    }
  }
  return runs.map((r) => `${r.start.toString(36)}:${r.widths.map((w) => (w.times > 1 ? `${w.width}*${w.times}` : `${w.width}`)).join(",")}`).join(";");
}

const files = await deckFontFiles();
const entries = DECK_FONTS.map((font) => {
  const [regular, bold] = [400, 700].map((weight) => readFont(files.find((f) => f.id === font.id && f.weight === weight).path));
  if (regular.unitsPerEm !== bold.unitsPerEm) throw new Error(`${font.family}: the two weights use different units`);
  return `  // ${font.family}: ${font.copyright}. SIL Open Font License 1.1.
  ${JSON.stringify(font.id)}: {
    unitsPerEm: ${regular.unitsPerEm},
    regular: ${JSON.stringify(pack(regular.advance))},
    bold: ${JSON.stringify(pack(bold.advance))},
  },`;
});

writeFileSync(FILE, `// GENERATED by scripts/generate-deck-font-widths.mjs: do not edit it, run \`node scripts/generate-deck-font-widths.mjs\`.
// How wide the characters of each deck font are (spec 0069; GLOSSARY: Deck, Theme), in the font's own units, measured
// from the openly licensed files named in scripts/deck-fonts.mjs. \`arial\` is measured from Arimo and \`georgia\` from
// Gelasio, which have the same widths. See NOTICE.

/** The width tables by the font a Theme names. */
export const FONT_WIDTHS = {
${entries.join("\n")}
} satisfies Record<string, { unitsPerEm: number; regular: string; bold: string }>;
`);
console.log(`Wrote ${FILE} (${DECK_FONTS.length} fonts).`);
