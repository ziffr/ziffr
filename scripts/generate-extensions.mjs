#!/usr/bin/env node
// Writes the registry of the Extensions built into Ziffr (spec 0042, ticket 3; GLOSSARY: Extension): packages/core/src/extensions.ts,
// from the folders under extensions/<author>/<name>, so that a folder cannot be left out of it by hand and a manifest
// that is missing or does not read fails here, not at run time. `node scripts/generate-extensions.mjs` rewrites the file;
// `--check` writes nothing and exits 1 when the file is not what the folders give (the core's extensions.test.ts runs the
// same comparison). The file is never edited by hand.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const FILE = "packages/core/src/extensions.ts";

/** The folders of the Extensions, as `author/name`, sorted. */
export function extensionFolders(root = ROOT) {
  const base = path.join(root, "extensions");
  const dirs = (p) => readdirSync(p, { withFileTypes: true }).filter((e) => e.isDirectory() && e.name !== "node_modules").map((e) => e.name);
  return dirs(base).flatMap((author) => dirs(path.join(base, author)).map((name) => `${author}/${name}`)).sort();
}

/** The text of the registry file for the folders under `root`; throws where a folder has no readable manifest or method. */
export function renderRegistry(root = ROOT) {
  const entries = extensionFolders(root).map((folder) => {
    const dir = path.join(root, "extensions", folder);
    if (!existsSync(path.join(dir, "extension.json"))) throw new Error(`extensions/${folder} has no extension.json`);
    const manifest = JSON.parse(readFileSync(path.join(dir, "extension.json"), "utf8"));
    if (manifest.id !== folder) throw new Error(`extensions/${folder}: the id in extension.json is “${manifest.id}”, and must be the folder's “${folder}”`);
    if (manifest.kind !== "method") throw new Error(`extensions/${folder}: only Methods are built in so far`);
    const exported = [...readFileSync(path.join(dir, "method.ts"), "utf8").matchAll(/^export function (\w+)/gm)].map((m) => m[1]);
    if (exported.length !== 1) throw new Error(`extensions/${folder}/method.ts must export exactly one function`);
    const local = folder.replace(/[^a-z0-9]+(.)/g, (_, c) => c.toUpperCase());
    return { folder, manifest, name: exported[0], local };
  });
  const indent = (text) => text.split("\n").join("\n    ");
  return `// GENERATED by scripts/generate-extensions.mjs from the folders under extensions/: do not edit it, run \`node scripts/generate-extensions.mjs\`.
// The registry of the Extensions built into this release (GLOSSARY: Extension): each one's manifest and Method, read by
// id. The core's own calculations take their Methods from here, and a recipe or a design will name one the same way.
${entries.map((e) => `import { ${e.name} as ${e.local} } from "@ziffr/extensions/${e.folder}/method";`).join("\n")}

/** The Extensions built into this release, in the order of their ids: id, manifest and Method. */
export const BUILT_IN_EXTENSIONS = [
${entries.map((e) => `  {\n    id: ${JSON.stringify(e.folder)},\n    manifest: ${indent(JSON.stringify(e.manifest, null, 2))},\n    method: ${e.local},\n  },`).join("\n")}
] as const;

/** The id of a built-in Extension. */
export type BuiltInId = (typeof BUILT_IN_EXTENSIONS)[number]["id"];

const METHODS = {
${entries.map((e) => `  ${JSON.stringify(e.folder)}: ${e.local},`).join("\n")}
} as const;

/** The Method of a built-in Extension, by its id, with the signature it has. */
export function builtInMethod<I extends BuiltInId>(id: I): (typeof METHODS)[I] {
  return METHODS[id];
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderRegistry();
  const target = path.join(ROOT, FILE);
  if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== text) {
      console.error(`${FILE} is not what extensions/ gives: run \`node scripts/generate-extensions.mjs\`.`);
      process.exit(1);
    }
    console.log(`${FILE} is up to date.`);
  } else {
    writeFileSync(target, text);
    console.log(`Wrote ${FILE}.`);
  }
}
